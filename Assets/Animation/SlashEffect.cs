using UnityEngine;
using UnityEngine.UI;
using DG.Tweening;

[RequireComponent(typeof(RectTransform), typeof(Image))]
public class UISlashEffectHDR : MonoBehaviour
{
    [Header("?????????")]
    [Tooltip("????????????")]
    public float totalDuration = 0.3f;

    [Tooltip("????????????????")]
    public Vector2 maxScale = new Vector2(1.5f, 1f);

    [Header("??????")]
    [Tooltip("??????????????????")]
    // ??????? (Bloom) ??????HDR???????????
    [ColorUsage(false, true)]
    public Color slashColor = new Color(2f, 2f, 2f, 1f); // ??HDR??????

    [Tooltip("??????????????????")]
    [ColorUsage(false, true)]
    public Color fadeOutColor = new Color(0f, 0f, 0f, 1f); // ??????????

    private RectTransform rectTransform;
    private Image effectImage;

    void Awake()
    {
        rectTransform = GetComponent<RectTransform>();
        effectImage = GetComponent<Image>();
        gameObject.SetActive(false);
    }

    /// <summary>
    /// ???????????????????????????
    /// </summary>
    /// <param name="angle">?????</param>
    /// <param name="customColor">????????????HDR???</param>
    public void PlaySlash(float angle = -45f, Color? customColor = null)
    {
        gameObject.SetActive(true);
        rectTransform.localRotation = Quaternion.Euler(0, 0, angle);
        rectTransform.localScale = new Vector3(0f, 0.2f, 1f);

        // --- ??????HDR??????????? ---
        Color finalColor = customColor ?? slashColor;
        // ???HDR??????????1f????
        effectImage.color = new Color(finalColor.r, finalColor.g, finalColor.b, 1f);

        Sequence seq = DOTween.Sequence();

        // --- ??/??????????????? ---
        seq.Append(rectTransform.DOScaleX(maxScale.x, totalDuration * 0.3f)
            .SetEase(Ease.OutExpo));
        seq.Join(rectTransform.DOScaleY(maxScale.y, totalDuration * 0.3f)
            .SetEase(Ease.OutQuad));

        // --- ????????????????? ---
        // ????????0.3f??????????fadeOutColor??/??????
        // ????????????????????????????????
        seq.Join(effectImage.DOColor(fadeOutColor, totalDuration * 0.7f)
            .SetEase(Ease.OutQuad)); // ???????

        // ????????????????????
        seq.Join(effectImage.DOFade(0f, totalDuration * 0.7f) // ???????0?
            .SetEase(Ease.InQuad));
        seq.Join(rectTransform.DOScaleX(maxScale.x * 1.2f, totalDuration * 0.7f)
    .SetEase(Ease.Linear));

        seq.OnComplete(() => {
            gameObject.SetActive(false);
        });
    }
}